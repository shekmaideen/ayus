function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function ThemeSync() {
  const dark = useClinic((s) => s.dark);
  useEffect(() => {
    document.documentElement.classList.toggle("dark", dark);
  }, [dark]);
  return null;
}

function AuthSync() {
  useEffect(() => {
    // Restore session from stored JWT token on every page load
    const token = sessionStorage.getItem("hc_token");
    if (token) {
      void useClinic.getState().loadAll();
    } else {
      useClinic.getState().clear();
    }
  }, []);
  return null;
}

function IdleSessionWatcher() {
  const navigate = useNavigate();
  const loggedIn = useClinic((s) => s.loggedIn);
  const loaded = useClinic((s) => s.loaded);

  useIdleTimeout({
    enabled: loaded && loggedIn,
    onTimeout: () => {
      sessionStorage.removeItem("hc_token");
      document.cookie = "hc_token=; path=/; max-age=0";
      useClinic.getState().clear();
      toast.info("Session expired", {
        description: "You have been logged out due to 15 minutes of inactivity.",
      });
      navigate({ to: "/", replace: true });
    },
  });

  return null;
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <ThemeSync />
      <AuthSync />
      <IdleSessionWatcher />
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <Outlet />
      <Toaster position="top-right" richColors />
    </QueryClientProvider>
  );
}
